package com.unuslumen.app.data.discovery

import android.content.Context
import android.net.wifi.WifiManager
import android.util.Log
import org.koin.core.annotation.Single
import java.io.File

/**
 * Discovered ARP device on the local network.
 */
data class ArpDevice(
    val ip: String,
    val mac: String,
    val manufacturer: String,
    val hostname: String,
    val discoveredAt: Long
)

/**
 * Reads the ARP table to map every IP to MAC address on the local network.
 * Identifies device manufacturers from MAC OUI (Organizationally Unique Identifier) prefixes.
 *
 * Works by ping-sweeping the subnet first to force ARP entries to populate,
 * then reading /proc/net/arp. Falls back to `ip neigh show` and DHCP info.
 */
@Single
class ArpDiscoveryManager(
    private val context: Context
) {

    /**
     * Discovers all devices on the local network by ping-sweeping the subnet
     * and reading the ARP table. Returns a list of devices with IP, MAC, and manufacturer.
     */
    fun discoverDevices(): List<ArpDevice> {
        val subnet = getSubnet()
        if (subnet.isBlank()) {
            Log.e(TAG, "Could not determine subnet")
            return emptyList()
        }

        Log.d(TAG, "Ping-sweeping subnet: $subnet")

        // Ping sweep to populate ARP table
        pingSweep(subnet)

        // Read ARP table
        val arpEntries = readArpTable()

        // If ARP table is empty, try ip neigh
        if (arpEntries.isEmpty()) {
            Log.d(TAG, "ARP table empty, trying ip neigh show")
            arpEntries.addAll(readIpNeigh())
        }

        // Enrich with manufacturer info from OUI
        val devices = arpEntries.map { (ip, mac) ->
            val manufacturer = lookupManufacturer(mac)
            ArpDevice(
                ip = ip,
                mac = mac,
                manufacturer = manufacturer,
                hostname = "",
                discoveredAt = System.currentTimeMillis()
            )
        }

        Log.d(TAG, "Discovered ${devices.size} devices via ARP")
        return devices.sortedBy { it.ip }
    }

    /**
     * Determines the subnet from the device's WiFi connection info.
     * Returns something like "192.168.0" (without the last octet).
     */
    @Suppress("DEPRECATION")
    private fun getSubnet(): String {
        try {
            val wifiManager = context.applicationContext.getSystemService(Context.WIFI_SERVICE) as? WifiManager
            if (wifiManager != null) {
                val dhcpInfo = wifiManager.dhcpInfo
                if (dhcpInfo != null) {
                    val ip = intToIp(dhcpInfo.ipAddress)
                    if (ip != "0.0.0.0") {
                        // Return first 3 octets
                        val parts = ip.split(".")
                        if (parts.size == 4) {
                            return "${parts[0]}.${parts[1]}.${parts[2]}"
                        }
                    }
                }
            }
        } catch (e: SecurityException) {
            Log.d(TAG, "No WiFi permission, trying /proc/net/arp for self IP")
        } catch (e: Exception) {
            Log.e(TAG, "Error getting subnet from WiFi", e)
        }

        // Fallback: try to get IP from ip addr
        try {
            val process = ProcessBuilder("sh", "-c", "ip addr show wlan0 2>/dev/null | grep 'inet ' | awk '{print \$2}'").start()
            val output = process.inputStream.bufferedReader().readText().trim()
            process.waitFor()
            if (output.contains("/")) {
                val ip = output.split("/")[0]
                val parts = ip.split(".")
                if (parts.size == 4) {
                    return "${parts[0]}.${parts[1]}.${parts[2]}"
                }
            }
        } catch (e: Exception) {
            Log.e(TAG, "Error getting IP from ip addr", e)
        }

        // Last resort: try ifconfig
        try {
            val process = ProcessBuilder("sh", "-c", "ifconfig wlan0 2>/dev/null | grep 'inet ' | awk '{print \$2}' | cut -d: -f2").start()
            val output = process.inputStream.bufferedReader().readText().trim()
            process.waitFor()
            val parts = output.split(".")
            if (parts.size == 4) {
                return "${parts[0]}.${parts[1]}.${parts[2]}"
            }
        } catch (e: Exception) {
            Log.e(TAG, "Error getting IP from ifconfig", e)
        }

        return ""
    }

    /**
     * Ping sweeps the subnet (1-254) to force ARP entries to populate.
     * Uses fast ping with 1 second timeout and parallel execution.
     */
    private fun pingSweep(subnet: String) {
        try {
            val command = StringBuilder()
            for (i in 1..254) {
                command.append("/system/bin/ping -c 1 -W 1 $subnet.$i >/dev/null 2>&1 &\n")
            }
            command.append("wait\n")

            val process = ProcessBuilder("sh", "-c", command.toString()).start()
            process.waitFor()
        } catch (e: Exception) {
            Log.e(TAG, "Error during ping sweep", e)
        }
    }

    /**
     * Reads the ARP table from /proc/net/arp.
     * Returns a list of (ip, mac) pairs.
     */
    private fun readArpTable(): MutableList<Pair<String, String>> {
        val entries = mutableListOf<Pair<String, String>>()

        try {
            val arpFile = File("/proc/net/arp")
            if (arpFile.exists()) {
                val lines = arpFile.readLines()
                // Skip header line
                for (line in lines.drop(1)) {
                    val parts = line.trim().split(Regex("\\s+"))
                    if (parts.size >= 4) {
                        val ip = parts[0]
                        val mac = parts[3]
                        // Skip entries with no MAC (00:00:00:00:00:00 or empty)
                        if (mac.isNotBlank() && mac != "00:00:00:00:00:00" && mac.contains(":")) {
                            entries.add(ip to mac.uppercase())
                        }
                    }
                }
            }
        } catch (e: Exception) {
            Log.e(TAG, "Error reading /proc/net/arp", e)
        }

        return entries
    }

    /**
     * Reads neighbour table using `ip neigh show`.
     * Fallback when /proc/net/arp is inaccessible.
     */
    private fun readIpNeigh(): MutableList<Pair<String, String>> {
        val entries = mutableListOf<Pair<String, String>>()

        try {
            val process = ProcessBuilder("sh", "-c", "ip neigh show 2>/dev/null").start()
            val output = process.inputStream.bufferedReader().readText()
            process.waitFor()

            for (line in output.lines()) {
                if (line.isBlank()) continue
                // Format: 192.168.0.1 dev wlan0 lladdr 00:1f:a4:xx:xx:xx REACHABLE
                val ipMatch = Regex("\\d+\\.\\d+\\.\\d+\\.\\d+").find(line)
                val macMatch = Regex("([0-9a-fA-F]{2}:){5}[0-9a-fA-F]{2}").find(line)
                if (ipMatch != null && macMatch != null) {
                    entries.add(ipMatch.value to macMatch.value.uppercase())
                }
            }
        } catch (e: Exception) {
            Log.e(TAG, "Error reading ip neigh", e)
        }

        return entries
    }

    /**
     * Looks up the manufacturer from the MAC address OUI prefix.
     * The OUI is the first 3 bytes (6 hex characters) of the MAC address.
     */
    private fun lookupManufacturer(mac: String): String {
        if (mac.isBlank() || !mac.contains(":")) return "Unknown"

        val oui = mac.split(":").take(3).joinToString(":").uppercase()
        return OUI_DATABASE[oui] ?: "Unknown"
    }

    private fun intToIp(i: Int): String {
        return "${i and 0xFF}.${i shr 8 and 0xFF}.${i shr 16 and 0xFF}.${i shr 24 and 0xFF}"
    }

