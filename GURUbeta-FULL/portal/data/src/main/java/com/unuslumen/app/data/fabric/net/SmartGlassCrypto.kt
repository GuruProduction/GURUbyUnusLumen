package com.unuslumen.app.data.fabric.net

import java.math.BigInteger
import java.security.KeyPair
import java.security.KeyPairGenerator
import java.security.MessageDigest
import java.security.SecureRandom
import java.security.interfaces.ECPublicKey
import java.security.spec.ECGenParameterSpec
import javax.crypto.Cipher
import javax.crypto.Mac
import javax.crypto.spec.IvParameterSpec
import javax.crypto.spec.SecretKeySpec

/**
 * The SmartGlass crypto context: how an Xbox and a client agree keys and sign what they send.
 *
 * THE EXACT DERIVATION, taken from the reference implementation rather than inferred:
 *
 *  1. An ephemeral P-384 key pair is generated by the client.
 *  2. ECDH against the console's certificate public key yields a 48-byte shared secret.
 *  3. THE SECRET IS SALTED WITH TWO FIXED CONSTANTS, one prepended and one appended:
 *       prepend D637F1AAE2F0418C
 *       append  A8F81A574E228AB7
 *  4. The salted secret is hashed with SHA-512, which gives 64 bytes.
 *  5. Those 64 bytes are cut three ways: bytes 0..15 are the AES-128 key, 16..31 are the IV
 *     key, and 32..63 are the HMAC-SHA-256 key.
 *
 * THE SALT IS TWO FIXED CONSTANTS, not anything derived at runtime. An earlier version of this
 * file used the client's own public key as the salt, which is invented and produces a key the
 * console will never agree with. Every console would have refused the connection, and the only
 * symptom would have been silence.
 *
 * THE IV IS NOT THE DERIVED IV DIRECTLY. For a channel message, the IV used to encrypt the
 * payload is the AES encryption of the first sixteen bytes of the message header under the
 * derived IV key. That is why [encryptForMessage] exists alongside [encrypt]: using the raw
 * derived IV produces a payload the console cannot decrypt.
 */
class SmartGlassCrypto private constructor(
    /** AES-128-CBC key, sixteen bytes. */
    val encryptionKey: ByteArray,
    /** The derived IV KEY, which is not the IV a message uses. */
    val ivKey: ByteArray,
    /** HMAC-SHA-256 key, thirty-two bytes. */
    val hashingKey: ByteArray,
    /** The client's ephemeral key pair, so its public key can travel in the request. */
    val keyPair: KeyPair,
) {

    companion object {

        /** The curve every SmartGlass console uses. */
        private const val CURVE = "secp384r1"

        /** The salt prepended to the shared secret before hashing. */
        private val SALT_PREFIX = byteArrayOf(
            0xD6.toByte(), 0x37, 0xF1.toByte(), 0xAA.toByte(),
            0xE2.toByte(), 0xF0.toByte(), 0x41, 0x8C.toByte(),
        )

        /** The salt appended to the shared secret before hashing. */
        private val SALT_SUFFIX = byteArrayOf(
            0xA8.toByte(), 0xF8.toByte(), 0x1A, 0x57, 0x4E, 0x22, 0x8A.toByte(), 0xB7.toByte(),
        )

        /** Build a context from a console's DER certificate. */
        fun create(consoleCertificate: ByteArray): Result {
            val keyPair = KeyPairGenerator.getInstance("EC").apply {
                initialize(ECGenParameterSpec(CURVE), SecureRandom())
            }.generateKeyPair()

            val consoleKey = consolePublicKey(consoleCertificate)
                ?: return Result(null, "The console certificate carries no usable P-384 public key.")

            val shared = runCatching { deriveSharedSecret(keyPair, consoleKey) }.getOrNull()
                ?: return Result(
                    null,
                    "The ECDH exchange with the console key failed, so no crypto context exists.",
                )

            val derived = deriveKeys(shared)

            return Result(
                SmartGlassCrypto(
                    encryptionKey = derived.encryptionKey,
                    ivKey = derived.ivKey,
                    hashingKey = derived.hashingKey,
                    keyPair = keyPair,
                ),
                null,
            )
        }

        data class Result(val crypto: SmartGlassCrypto?, val reason: String?)

        /** The three keys, exactly as the reference implementation slices the hash. */
        data class DerivedKeys(
            val encryptionKey: ByteArray,
            val ivKey: ByteArray,
            val hashingKey: ByteArray,
        ) {
            override fun equals(other: Any?): Boolean {
                if (this === other) return true
                if (other !is DerivedKeys) return false
                return encryptionKey.contentEquals(other.encryptionKey) &&
                    ivKey.contentEquals(other.ivKey) &&
                    hashingKey.contentEquals(other.hashingKey)
            }

            override fun hashCode(): Int = encryptionKey.contentHashCode()
        }

        /**
         * Salt the shared secret with both constants, hash it with SHA-512, and cut it in three.
         *
         * The slice sizes matter: the HMAC key is THIRTY-TWO bytes, not sixteen, because the
         * hash is sixty-four bytes and the first thirty-two are the two AES keys.
         */
        fun deriveKeys(sharedSecret: ByteArray): DerivedKeys {
            val salted = SALT_PREFIX + sharedSecret + SALT_SUFFIX
            val hash = MessageDigest.getInstance("SHA-512").digest(salted)
            return DerivedKeys(
                encryptionKey = hash.copyOfRange(0, 16),
                ivKey = hash.copyOfRange(16, 32),
                hashingKey = hash.copyOfRange(32, 64),
            )
        }

        /** A context built from already-derived keys, for a test. */
        internal fun forTesting(keys: DerivedKeys, keyPair: KeyPair): SmartGlassCrypto =
            SmartGlassCrypto(
                encryptionKey = keys.encryptionKey,
                ivKey = keys.ivKey,
                hashingKey = keys.hashingKey,
                keyPair = keyPair,
            )

        /** The console's public key, from the DER certificate in its discovery reply. */
        fun consolePublicKey(certificate: ByteArray): ECPublicKey? = runCatching {
            val factory = java.security.cert.CertificateFactory.getInstance("X.509")
            val cert = factory.generateCertificate(certificate.inputStream()) as? java.security.cert.X509Certificate
            cert?.publicKey as? ECPublicKey
        }.getOrNull()

        /** The P-384 shared secret, which is the raw ECDH output. */
        fun deriveSharedSecret(client: KeyPair, consoleKey: ECPublicKey): ByteArray {
            val keyAgreement = javax.crypto.KeyAgreement.getInstance("ECDH")
            keyAgreement.init(client.private)
            keyAgreement.doPhase(consoleKey, true)
            return keyAgreement.generateSecret()
        }

        /**
         * A P-384 public key as the protocol carries it: 96 raw bytes, X then Y, NO prefix.
         *
         * The reference implementation takes the uncompressed point and drops its first byte.
         * Sending 97 bytes with the 0x04 in front makes the console read the following field one
         * byte early and reject the request, which is why this returns 96.
         */
        fun encodeKeyForRequest(key: ECPublicKey): ByteArray {
            val out = ByteArray(96)
            writeFixed(key.w.affineX, out, 0, 48)
            writeFixed(key.w.affineY, out, 48, 48)
            return out
        }

        /** Write a BigInteger into a fixed-width big-endian slot, left padded with zeros. */
        private fun writeFixed(value: BigInteger, target: ByteArray, offset: Int, width: Int) {
            val bytes = value.toByteArray()
            val source = if (bytes.size > width && bytes[0] == 0.toByte()) {
                bytes.copyOfRange(bytes.size - width, bytes.size)
            } else {
                bytes
            }
            val start = offset + width - source.size
            source.copyInto(target, start)
        }
    }

    /**
     * The IV a message uses: AES encrypt the first sixteen bytes of the header under the IV key.
     *
     * THIS IS THE STEP THAT IS EASY TO SKIP. The derived IV key is not the IV. A payload
     * encrypted with the wrong IV decrypts to garbage on the console side, and the console
     * simply drops the message.
     */
    fun messageIv(header: ByteArray): ByteArray {
        val first16 = header.copyOfRange(0, minOf(16, header.size))
        val cipher = Cipher.getInstance("AES/CBC/NoPadding")
        // A zero IV, because this operation derives an IV rather than enciphering data.
        cipher.init(
            Cipher.ENCRYPT_MODE,
            SecretKeySpec(ivKey, "AES"),
            IvParameterSpec(ByteArray(16)),
        )
        val padded = if (first16.size % 16 == 0) first16 else first16 + ByteArray(16 - first16.size % 16)
        return cipher.doFinal(padded)
    }

    /** Encrypt a payload with an explicit IV, which is what a message needs. */
    fun encryptWith(iv: ByteArray, payload: ByteArray): ByteArray {
        val padded = if (payload.size % 16 == 0) payload else payload + ByteArray(16 - payload.size % 16)
        val cipher = Cipher.getInstance("AES/CBC/NoPadding")
        cipher.init(
            Cipher.ENCRYPT_MODE,
            SecretKeySpec(encryptionKey, "AES"),
            IvParameterSpec(iv),
        )
        return cipher.doFinal(padded)
    }

    /** Decrypt a payload with an explicit IV. */
    fun decryptWith(iv: ByteArray, payload: ByteArray): ByteArray? {
        if (payload.isEmpty() || payload.size % 16 != 0) return null
        return runCatching {
            val cipher = Cipher.getInstance("AES/CBC/NoPadding")
            cipher.init(
                Cipher.DECRYPT_MODE,
                SecretKeySpec(encryptionKey, "AES"),
                IvParameterSpec(iv),
            )
            cipher.doFinal(payload)
        }.getOrNull()
    }

    /**
     * The HMAC-SHA-256 digest a message carries.
     *
     * The reference implementation hashes the protected payload and appends the digest to the
     * packet, so the signature covers exactly the ciphertext the console will decrypt.
     */
    fun sign(protectedPayload: ByteArray): ByteArray {
        val mac = Mac.getInstance("HmacSHA256")
        mac.init(SecretKeySpec(hashingKey, "HmacSHA256"))
        return mac.doFinal(protectedPayload)
    }

    /** Verify in constant time, so a wrong key cannot be probed by timing. */
    fun verify(protectedPayload: ByteArray, signature: ByteArray): Boolean {
        val expected = sign(protectedPayload)
        if (expected.size != signature.size) return false
        var difference = 0
        for (index in expected.indices) {
            difference = difference or (expected[index].toInt() xor signature[index].toInt())
        }
        return difference == 0
    }
}
