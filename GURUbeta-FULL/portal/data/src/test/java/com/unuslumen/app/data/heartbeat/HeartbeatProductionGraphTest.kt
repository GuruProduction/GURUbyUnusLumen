package com.unuslumen.app.data.heartbeat

import android.app.Application
import androidx.test.core.app.ApplicationProvider
import com.unuslumen.app.data.di.AiDataModule
import com.unuslumen.app.domain.repository.HeartbeatPromptRepository
import org.junit.Assert.assertTrue
import org.junit.Test
import org.junit.runner.RunWith
import org.koin.android.ext.koin.androidContext
import org.koin.core.error.NoDefinitionFoundException
import org.koin.dsl.koinApplication
import org.koin.ksp.generated.module
import org.robolectric.RobolectricTestRunner

/**
 * The heartbeat prompt repository must resolve from the REAL generated module.
 *
 * WHY THIS IS A DIFFERENT TEST FROM THE ONE BESIDE IT. The other test builds its own
 * container and binds the implementation by hand, which proves the class works and
 * proves nothing about the app. The app resolves from `AiDataModule`, which is
 * generated by Koin's KSP pass from `@Module @ComponentScan("com.unuslumen.app.data")`.
 *
 * That generator is the thing that has already failed this codebase: it produced
 * empty modules for Ottio and for Agents across a Gradle boundary, and both rooms
 * crashed on open with "No definition found for type" while every test and every
 * build was green. A beat has no screen to crash on, so the same fault here does not
 * show a message, it shows a half hour of silence.
 *
 * So this asks the generated graph itself for the interface, with nothing bound by
 * hand. If the scan ever stops producing this definition, this test fails.
 */
@RunWith(RobolectricTestRunner::class)
class HeartbeatProductionGraphTest {

    @Test
    fun `the generated data module binds the heartbeat prompt repository`() {
        val koin = koinApplication {
            androidContext(ApplicationProvider.getApplicationContext<Application>())
            // BOTH MODULES, IN THE ORDER THE APP LOADS THEM. The repository takes a
            // DAO, and that DAO is bound by databaseModule rather than by the data
            // scan. Loading only the data module fails with "No definition found for
            // type HeartbeatPromptDao", which is a fault in this test rather than in
            // the app: GuruApplication registers databaseModule before aiDataModule,
            // so the DAO is present long before any beat can run.
            modules(
                com.unuslumen.app.database.di.databaseModule,
                AiDataModule().module,
            )
        }.koin

        val resolved = try {
            koin.get<HeartbeatPromptRepository>()
            true
        } catch (e: NoDefinitionFoundException) {
            false
        }

        assertTrue(
            "HeartbeatPromptRepository did not resolve from the generated AiDataModule. The " +
                "heartbeat run service injects it, so every beat would end inside its coroutine " +
                "with only a log line, and the phone would show a heartbeat that never fires.",
            resolved,
        )
    }
}
